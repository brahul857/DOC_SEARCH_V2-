def find_keyword_matches(pages: List[Dict[str, Any]], keyword: str, context_chars: int = 180):
    """Return every case-insensitive occurrence and a readable context snippet."""
    matches = []
    pattern = re.compile(re.escape(keyword), re.IGNORECASE)
    for item in pages:
        text = item["text"]
        for match in pattern.finditer(text):
            start = max(0, match.start() - context_chars)
            end = min(len(text), match.end() + context_chars)
            snippet = re.sub(r"\s+", " ", text[start:end]).strip()
            matches.append({
                "Keyword": keyword,
                "Page": item["page"],
                "Matched text": match.group(0),
                "Context": snippet
            })
    return matches


def format_template_fields(raw_fields):
    fields = []
    seen = set()
    for raw_field in raw_fields:
        for field in re.split(r"[,;]", str(raw_field)):
            field = re.sub(r"\s+", " ", field).strip(" \t:-")
            normalized = re.sub(r"[^a-z0-9]+", "", field.lower())
            if field and normalized and normalized not in seen:
                seen.add(normalized)
                fields.append(field)
    return fields


def extract_template_keyword_values(
    pages: List[Dict[str, Any]],
    keywords: List[str],
) -> pd.DataFrame:
    """Extract a value following each template keyword in PDF text."""
    rows = []
    for keyword in keywords:
        keyword = keyword.strip()
        if not keyword:
            continue

        value = ""
        page_number = ""
        for item in pages:
            value = extract_template_field_value([item], keyword)
            if value:
                page_number = item["page"]
                break

        if value:
            rows.append({
                "Keyword": keyword,
                "Value": value,
                "Page": page_number,
            })
        else:
            rows.append({
                "Keyword": keyword,
                "Value": "Not found",
                "Page": "",
            })
    return pd.DataFrame(rows, columns=["Keyword", "Value", "Page"])

def extract_labeled_values(pages):
    """Extract common GeM fields and generic label: value lines."""
    known_labels = [
        "Contract No.", "Generated Date", "Procurement Mode",
        "Seller Name", "Service Start Date", "Service End Date",
        "Brand", "Model",
        "Buyer", "Service Provider",
        "Type", "Ministry", "Department", "Organisation Name", "Office Zone",
        "Designation", "Contact No.", "Email ID", "GSTIN", "Address",
        "IFD Concurrence", "Administrative Approval", "Financial Approval",
        "Role", "Payment Mode", "GeM Seller ID", "Company Name",
        "MSME Registration No.", "MSE Social Category / Gender",
        "GST / Tax invoice to be raised in the name of",
        "Delivery Instructions", "Item Description", "Ordered Qty", "Unit",
        "Unit Price", "Tax (INR)", "Total Price", "Total Order Value (INR)",
        "Consignee / Designation", "Contact / Email", "Quantity",
        "Delivery Start", "Delivery By", "Delivery Contact", "Delivery Note",
        "Description of Stores", "Processor", "RAM", "Storage", "Display",
        "Operating System", "Connectivity", "Keyboard / Mouse", "Warranty",
        "Installation", "Country of Origin", "Delivery Period", "Inspection",
        "Acceptance",
    ]
    known_lookup = {re.sub(r"[^a-z0-9]+", "", label.lower()): label for label in known_labels}

    lines = []
    for page in pages:
        for line in page["text"].splitlines():
            line = re.sub(r"\s+", " ", line).strip()
            if line:
                lines.append(line)

    rows = []
    seen_fields = set()

    def add(field, value):
        value = re.sub(r"\s+", " ", value or "").strip(" \t:-")
        if value and field not in seen_fields:
            seen_fields.add(field)
            rows.append({"Field": field, "Extracted value": value})

    full_text = "\n".join(p["text"] for p in pages)
    normalized_text = re.sub(r"[ \t]+", " ", full_text)
    for field, pattern in (
        ("Contract No.", r"Contract\s*No\.?\s*:\s*([A-Za-z0-9][A-Za-z0-9\-]+)"),
        ("Generated Date", r"Generated\s*Date\s*:\s*(\d{1,2}-[A-Za-z]+-\d{4})"),
        ("Total Order Value (INR)", r"Total\s+Order\s+Value\s*\(INR\)\s*([0-9][0-9,]*(?:\.\d{1,2})?)"),
        ("Seller Name", r"Seller\s+Name\s*[:\-]?\s*([^\n]{2,120})"),
        ("Service Start Date", r"Service\s+Start\s+Date\s*[:\-]?\s*(\d{1,2}(?:[-/][A-Za-z0-9]{2,12}[-/]\d{4}|[-/]\d{1,2}[-/]\d{4}))"),
        ("Service End Date", r"Service\s+End\s+Date\s*[:\-]?\s*(\d{1,2}(?:[-/][A-Za-z0-9]{2,12}[-/]\d{4}|[-/]\d{1,2}[-/]\d{4}))"),
        ("Brand", r"Brand\s*[:\-]?\s*([^\n]{1,80})"),
        ("Model", r"Model\s*[:\-]?\s*([^\n]{1,80})"),
        ("Quantity", r"Quantity\s*[:\-]?\s*([0-9][0-9,]*(?:\.\d+)?)"),
        ("Warranty", r"Warranty\s*[:\-]?\s*(.{1,80})"),
        ("Buyer", r"(?im)^\s*\d+\.\s*Buyer\s*:\s*(.{2,300})$"),
        ("Service Provider", r"(?im)^\s*\d+\.\s*Service\s*Provider\s*:\s*(.{2,300})$"),
    ):
        match = re.search(pattern, normalized_text, flags=re.IGNORECASE)
        if match:
            add(field, match.group(1))

    for index, line in enumerate(lines):
        if ":" in line:
            label, value = line.split(":", 1)
            label = re.sub(r"^\s*\d+\.\s*", "", label).strip()
            label_key = re.sub(r"[^a-z0-9]+", "", label.lower())
            field = known_lookup.get(label_key)
            if field:
                add(field, value)
            elif len(label.strip()) <= 60:
                add(label.strip().rstrip("."), value)

    for index, line in enumerate(lines):
        key = re.sub(r"[^a-z0-9]+", "", line.lower()).rstrip(".")
        field = known_lookup.get(key)
        if not field:
            continue
        if field in seen_fields:
            continue

        values = []
        for next_line in lines[index + 1:index + 4]:
            next_key = re.sub(r"[^a-z0-9]+", "", next_line.lower()).rstrip(".")
            if next_key in known_lookup:
                break
            if next_line.endswith(":"):
                break
            if next_line.upper() == next_line and len(next_line) > 3:
                break
            values.append(next_line)
            if len(values) >= 1 and field in {
                "Type", "Ministry", "Department", "Designation", "Contact No.",
                "Email ID", "GSTIN", "Role", "Payment Mode", "GeM Seller ID",
                "Company Name", "MSME Registration No.", "Processor", "RAM",
                "Storage", "Display", "Operating System", "Connectivity",
                "Keyboard / Mouse", "Warranty", "Installation",
                "Country of Origin", "Delivery Period", "Inspection", "Acceptance",
                "Seller Name", "Service Start Date", "Service End Date",
                "Brand", "Model", "Quantity",
                "Buyer", "Service Provider",
            }:
                break
        add(field, " ".join(values))

    full_text = "\n".join(p["text"] for p in pages)
    normalized_text = re.sub(r"[ \t]+", " ", full_text)
    for field, pattern in (
        ("Contract No.", r"Contract\s*No\.?\s*:\s*([A-Za-z0-9][A-Za-z0-9\-]+)"),
        ("Generated Date", r"Generated\s*Date\s*:\s*(\d{1,2}-[A-Za-z]+-\d{4})"),
        ("Total Order Value (INR)", r"Total\s+Order\s+Value\s*\(INR\)\s*([0-9][0-9,]*(?:\.\d{1,2})?)"),
        ("Company Name", r"Company\s+Name\s*\n\s*([^\n]{2,100})"),
    ):
        match = re.search(pattern, normalized_text, flags=re.IGNORECASE)
        if match:
            add(field, match.group(1))

    return pd.DataFrame(rows, columns=["Field", "Extracted value"])


